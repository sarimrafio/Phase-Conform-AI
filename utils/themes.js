export function getActiveThemeConfig(themeId = 'midnight', isDark = true) {
  const palette = THEME_PALETTES.find(p => p.id === themeId) || THEME_PALETTES[0];
  const modeKey = isDark ? 'dark' : 'light';
  const cfg = palette[modeKey];
  return {
    id: palette.id,
    name: palette.name,
    tag: palette.tag,
    dotColor: palette.dotColor,
    isDark,
    neuShadowDark: cfg.neuShadowDark || (isDark ? 'rgba(0, 0, 0, 0.75)' : 'rgba(163, 177, 198, 0.55)'),
    neuShadowLight: cfg.neuShadowLight || (isDark ? 'rgba(255, 255, 255, 0.05)' : 'rgba(255, 255, 255, 0.95)'),
    neuBorder: cfg.neuBorder || (isDark ? 'rgba(255, 255, 255, 0.07)' : 'rgba(255, 255, 255, 0.85)'),
    neuAccentGlow: cfg.neuAccentGlow || cfg.accentPrimary,
    ...cfg
  };
}
